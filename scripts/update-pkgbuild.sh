#!/usr/bin/env bash
# Generate packaging/aur/PKGBUILD from Cargo.toml — the single source of
# truth for version/description/license/URL — so the package definition can
# never drift from the crate metadata.
#
# Portix is a local project; packaging is only needed when you want to
# install it as an Arch package or publish it to the AUR. The PKGBUILD is
# the `portix-git` style: it builds from the git repo, so it always tracks
# the latest commit (pkgver comes from `git describe`).
#
# Usage:
#   scripts/update-pkgbuild.sh            # (re)generate packaging/aur/PKGBUILD
#   scripts/update-pkgbuild.sh --check    # exit 1 if the PKGBUILD is stale
#   scripts/update-pkgbuild.sh --print    # print to stdout, write nothing
#
# Install the package locally:  cd packaging/aur && makepkg -si
set -euo pipefail

usage() {
    # Print the leading comment header only: a fixed line range leaked
    # `set -euo pipefail` and code into --help as soon as the header changed.
    awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "${BASH_SOURCE[0]}"
}

MODE="write"
for arg in "$@"; do
    case "$arg" in
        --check) MODE="check" ;;
        --print) MODE="print" ;;
        -h | --help) usage; exit 0 ;;
        *) echo "unknown argument: $arg" >&2; exit 2 ;;
    esac
done

cd "$(dirname "$0")/.."

# --- extract metadata from Cargo.toml ----------------------------------------
get_field() {
    grep -m1 "^$1 = " Cargo.toml | sed -E 's/^[^=]*= *"([^"]*)".*/\1/'
}
VERSION="$(get_field version)"
DESC="$(get_field description)"
LICENSE="$(get_field license)"
URL="$(get_field repository)"

if [ -z "$VERSION" ] || [ -z "$DESC" ] || [ -z "$URL" ]; then
    echo "could not extract version/description/repository from Cargo.toml" >&2
    exit 1
fi

# SPDX "MIT OR Apache-2.0" -> 'MIT' 'Apache-2.0' (each license its own element)
LICENSES="$(printf '%s' "$LICENSE" | awk '{ gsub(/ OR /, "\x27 \x27"); print "\x27" $0 "\x27" }')"

# --- render the PKGBUILD -----------------------------------------------------
# `\$srcdir`/`\$pkgdir` are escaped: they are makepkg variables, expanded when
# the PKGBUILD runs, not here.
PKGBUILD_CONTENT=$(cat <<EOF
# Maintainer: Sergio Jáuregui <sergioja2003@gmail.com>
# Generated by scripts/update-pkgbuild.sh from Cargo.toml — do not edit by hand.
pkgname=portix-git
pkgver=${VERSION}
pkgrel=1
pkgdesc="${DESC}"
arch=('x86_64')
url="${URL}"
license=(${LICENSES})
depends=('glibc' 'gcc-libs')
optdepends=('xdg-utils: desktop opener fallback for the "o" key'
            'wl-clipboard: copy a service URL on Wayland (the "y" key)'
            'xclip: copy a service URL on X11 (the "y" key)'
            'xsel: copy a service URL on X11 (the "y" key)')
makedepends=('cargo' 'rust' 'git')   # 'git': the source is a VCS (git+) clone
provides=('portix')
conflicts=('portix')
source=("portix-git::git+${URL}.git")
sha256sums=('SKIP')

pkgver() {
    cd "\$srcdir/portix-git"
    git describe --always --tags 2>/dev/null | sed 's/^v//' || echo "${VERSION}"
}

build() {
    cd "\$srcdir/portix-git"
    cargo build --release --locked
}

package() {
    cd "\$srcdir/portix-git"
    install -Dm755 target/release/portix "\$pkgdir/usr/bin/portix"
    install -d "\$pkgdir/usr/share/applications"
    sed -e 's|@PORTIX_BIN@|/usr/bin/portix|g' \
        -e 's|@PORTIX_LAUNCH@|ghostty -e sudo /usr/bin/portix|g' \
        -e 's|@PORTIX_UPDATE@|ghostty -e sudo /usr/bin/portix --update --all-contexts|g' \
        packaging/desktop/portix.desktop.in \
        > "\$pkgdir/usr/share/applications/portix.desktop"
    install -Dm644 packaging/desktop/icons/hicolor/256x256/apps/portix.png \
        "\$pkgdir/usr/share/icons/hicolor/256x256/apps/portix.png"
    install -Dm644 packaging/desktop/icons/hicolor/512x512/apps/portix.png \
        "\$pkgdir/usr/share/icons/hicolor/512x512/apps/portix.png"
    install -Dm644 packaging/desktop/index.theme \
        "\$pkgdir/usr/share/icons/hicolor/index.theme"
    install -Dm644 README.md "\$pkgdir/usr/share/doc/portix-git/README.md"
    install -Dm644 LICENSE-MIT "\$pkgdir/usr/share/licenses/portix-git/LICENSE-MIT"
    install -Dm644 LICENSE-APACHE "\$pkgdir/usr/share/licenses/portix-git/LICENSE-APACHE"
}
EOF
)

case "$MODE" in
    print)
        printf '%s\n' "$PKGBUILD_CONTENT"
        ;;
    check)
        if [ -f packaging/aur/PKGBUILD ] && cmp -s packaging/aur/PKGBUILD <(printf '%s\n' "$PKGBUILD_CONTENT"); then
            echo "packaging/aur/PKGBUILD is up to date (Cargo.toml)"
        else
            echo "packaging/aur/PKGBUILD is STALE — run scripts/update-pkgbuild.sh" >&2
            exit 1
        fi
        ;;
    write)
        mkdir -p packaging/aur
        printf '%s\n' "$PKGBUILD_CONTENT" > packaging/aur/PKGBUILD
        echo "wrote packaging/aur/PKGBUILD (pkgver base ${VERSION})"
        ;;
esac
